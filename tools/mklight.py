"""Builds a3light.css: a 'paper' light theme generated from a3c.css + a3.css.
Every rule that paints a dark-theme colour gets a light override under body.lightui."""
import re, sys
SRC = ['a3c.css', 'a3.css']
INK = (28, 34, 40)

def tr_color(m, prop):
    s = m.group(0)
    r = re.match(r'rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+))?\s*\)', s)
    if r:
        R, G, B = int(r[1]), int(r[2]), int(r[3]); A = float(r[4]) if r[4] else 1.0
        if (R, G, B) == (255, 255, 255):
            if prop in ('color',): return 'rgba(28,34,40,%.2f)' % A
            return 'rgba(28,34,40,%.3f)' % min(.5, A * .55)
        if (R, G, B) == (244, 236, 220): return 'rgba(28,34,40,%.2f)' % A
        if R < 60 and G < 60 and B < 70 and A < 1 and prop.startswith('background'):   # dark glass tint
            return 'rgba(255,255,255,%.2f)' % min(.82, A + .38)
        if R < 60 and G < 60 and B < 70 and 'shadow' in prop:
            return 'rgba(60,40,30,%.3f)' % (A * .35)
        return s
    h = s.lower()
    if h in ('#f4ecdc',): return '#1c2228'
    if h in ('#1b2228', '#14202a', '#0b1a12', '#0b0f14', '#24100a', '#1c2228'): return '#f4ecdc'
    if h in ('#c3d3da',): return 'rgba(28,34,40,.62)'
    if h in ('#93acb8',): return 'rgba(28,34,40,.45)'
    return s

COL = re.compile(r'rgba?\([^)]*\)|#[0-9a-fA-F]{6}\b')
def tr_decls(body):
    out = []
    for d in body.split(';'):
        if ':' not in d: continue
        prop, val = d.split(':', 1); p = prop.strip().lower()
        if p.startswith('--') or p in ('filter', 'animation', 'transition', 'mask', '-webkit-mask', 'transform'): continue
        if not COL.search(val): continue
        if p.startswith('-webkit-backdrop') or p.startswith('backdrop'): continue
        nv = COL.sub(lambda m: tr_color(m, p), val)
        if nv != val: out.append(prop.strip() + ':' + nv.strip())
    return ';'.join(out)

def pref(sel):
    out = []
    for x in sel.split(','):
        x = x.strip()
        if not x: continue
        if x.startswith(':root') or x.startswith('html'): continue
        if x.startswith('body'): out.append('body.lightui' + x[4:] if not x.startswith('body.lightui') else x)
        else: out.append('body.lightui ' + x)
    return ', '.join(out)

def walk(css, wrap=None, res=None):
    i = 0; n = len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: break
        head = css[i:j].strip()
        # find matching brace
        depth = 1; k = j + 1
        while k < n and depth:
            if css[k] == '{': depth += 1
            elif css[k] == '}': depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        head = re.sub(r'/\*.*?\*/', '', head, flags=re.S).strip()
        if head.startswith('@media') or head.startswith('@supports'):
            walk(body, head, res)
        elif head.startswith('@'):
            pass
        else:
            if re.search(r'\.a3w(c|ch|cb|bg|big|nx)\b|\.a3wc ', head): i = k; continue  # wallet cards keep their own colours
            d = tr_decls(body)
            sel = pref(head)
            if d and sel: res.append((wrap, sel + '{' + d + '}'))
        i = k
    return res

